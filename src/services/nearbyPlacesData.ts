/**
 * Calculate distance in km between two lat/lng points using Haversine formula
 */
export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

/**
 * Estimate travel time in minutes based on urban traffic average (28 km/h drive, 4.5 km/h walk)
 */
export function estimateTravelTime(distanceKm: number): { driveMin: number; walkMin: number } {
  const driveMin = Math.max(2, Math.round((distanceKm / 28) * 60));
  const walkMin = Math.round((distanceKm / 4.5) * 60);
  return { driveMin, walkMin };
}
